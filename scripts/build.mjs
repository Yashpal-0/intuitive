#!/usr/bin/env node
// Builds both plugins from the single source of truth in shared/*.md.
//
//   node scripts/build.mjs           regenerate the derived files
//   node scripts/build.mjs --check   exit 1 if any derived file is out of date (for CI)
//
// Derived files:
//   claude-code/output-styles/intuitive.md      main guidelines (forced plugin output style)
//   claude-code/hooks/subagent-start.sh         compact guidelines for every subagent
//   claude-code/hooks/user-prompt-submit.sh     one-line per-prompt reminder
//   opencode/index.ts                           the <generated> block with all three texts

import { readFileSync, writeFileSync, chmodSync, existsSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const check = process.argv.includes("--check")
const read = (file) => readFileSync(join(root, file), "utf8").replace(/\r\n/g, "\n").trim()

const guidelines = read("shared/intuitive.md")
const subagent = read("shared/subagent.md")
const reminder = read("shared/reminder.md")
const compaction = read("shared/compaction.md")

// Claude Code shows output styles under its own "# Output Style: ..." heading, so drop our H1.
const styleBody = guidelines.replace(/^# .*\n+/, "")

const outputStyle = `---
name: intuitive
description: Grasps what you actually mean, does what you'd expect, and answers so it clicks on the first read.
keep-coding-instructions: true
force-for-plugin: true
---

${styleBody}
`

const hookScript = ({ event, what, option, envVar, text }) => `#!/usr/bin/env bash
# Intuitive: ${what}
# Generated by scripts/build.mjs from shared/*.md. Edit those files, then rebuild.
# Turn off with \`/plugin configure intuitive@intuitive\` (${option} = false), or set
# ${envVar}=off in the "env" block of a settings.json (the env var wins when set).
setting="\${${envVar}:-\${CLAUDE_PLUGIN_OPTION_${option.toUpperCase()}:-on}}"
case "$(printf '%s' "$setting" | tr '[:upper:]' '[:lower:]')" in
  false | off | 0 | no | disabled) exit 0 ;;
esac
cat <<'JSON'
${JSON.stringify({ hookSpecificOutput: { hookEventName: event, additionalContext: text } })}
JSON
`

// Text inside a TS template literal: escape backslashes, backticks and \${.
const literal = (text) => "`" + text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`"

const indexPath = "opencode/index.ts"
const index = readFileSync(join(root, indexPath), "utf8")
const block = /(\/\/ <generated>[^\n]*\n)[\s\S]*?(\/\/ <\/generated>)/
if (!block.test(index)) throw new Error(`${indexPath}: <generated> markers not found`)
const generatedIndex = index.replace(
  block,
  (_, open, close) =>
    open +
    `const GUIDELINES = ${literal(guidelines)}\n\n` +
    `const SUBAGENT_GUIDELINES = ${literal(subagent)}\n\n` +
    `const COMPACTION_GUIDANCE = ${literal(compaction)}\n` +
    close,
)

const outputs = [
  ["claude-code/output-styles/intuitive.md", outputStyle],
  [
    "claude-code/hooks/subagent-start.sh",
    hookScript({
      event: "SubagentStart",
      what: "gives every subagent a compact version of the guidelines.",
      option: "subagents",
      envVar: "INTUITIVE_SUBAGENTS",
      text: subagent,
    }),
    true,
  ],
  [
    "claude-code/hooks/user-prompt-submit.sh",
    hookScript({
      event: "UserPromptSubmit",
      what: "adds a one-line style reminder to every prompt so long sessions never drift.",
      option: "reminder",
      envVar: "INTUITIVE_REMINDER",
      text: reminder,
    }),
    true,
  ],
  [indexPath, generatedIndex],
]

let stale = 0
for (const [file, content, executable] of outputs) {
  const target = join(root, file)
  const current = existsSync(target) ? readFileSync(target, "utf8") : null
  if (current === content) continue
  if (check) {
    console.error(`out of date: ${relative(root, target)}`)
    stale++
    continue
  }
  writeFileSync(target, content)
  if (executable) chmodSync(target, 0o755)
  console.log(`wrote ${relative(root, target)}`)
}

// Claude Code replaces hook context over 10,000 characters with a file path and a preview.
for (const [name, text] of Object.entries({ subagent, reminder })) {
  if (text.length > 9000) throw new Error(`shared/${name}.md is ${text.length} characters; keep hook text under 9,000`)
}
const chars = { guidelines: guidelines.length, subagent: subagent.length, reminder: reminder.length, compaction: compaction.length }
if (check && stale) process.exit(1)
if (!check) console.log(`sizes (chars): ${JSON.stringify(chars)}`)
